#!/usr/bin/env python3
"""The style's values are written once, in style/tokens.toml; this makes
from them what the toolkit reads:

  python3 tools/make_style.py            writes src/<package>/gui/style.css and gui/style_values.py
  python3 tools/make_style.py --check    writes nothing: says what is not as the tokens give, and returns 1

gui/style.css holds the values as CSS variables (--space-m, --radius-card);
gui/style_values.py holds them for the code (SPACE_M, RADIUS_CARD). The
app's own rules are written by hand in gui/app.css and take their measures
and colours from the variables only: --check lists what is written by hand
there, and the spacings written as numbers in the gui modules.

The format (the template's docs/10-stile-proposta.md) is the same in the
GTK and in the Qt model; each has its own generator.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "style" / "tokens.toml"
PACKAGE = ROOT / "src" / "scriba"

FORMAT = 1
# the sections, in the order they are written out; each with the prefix of
# its CSS variables and the unit of its numbers
SECTIONS = {"space": ("space", "px"), "radius": ("radius", "px"), "type": ("text", "px"), "icon": ("icon", "px"),
            "line": ("line", "px"), "size": ("size", "px"), "motion": ("motion", "ms"), "color": ("app", "")}
SPACE = ("xxs", "xs", "s", "m", "l", "xl", "xxl", "xxxl")       # the closed scale, smallest first
WEIGHTS = ("regular", "semibold", "bold")                       # in [type]: a weight, not a size
SCHEMES = ("light", "dark")
KEY = re.compile(r"[a-z][a-z0-9_]*\Z")
COLOUR = re.compile(r"#(?:[0-9a-f]{6}|[0-9a-f]{8})\Z")
HEADER = "Generated by tools/make_style.py from style/tokens.toml. Do not edit:\n" \
         "change the tokens and run the tool (tests/test_style.py compares)."


class TokenError(ValueError):
    """What is wrong in the tokens, with the key it is about."""


def _number(where: str, value, lowest: int = 0, highest: int = 10000) -> None:
    if isinstance(value, bool) or not isinstance(value, int) or not lowest <= value <= highest:
        raise TokenError(f"{where}: a whole number from {lowest} to {highest}, not {value!r}")


def _colour(where: str, value) -> None:
    if value != "" and not (isinstance(value, str) and COLOUR.match(value)):
        raise TokenError(f'{where}: "#rrggbb" or "#rrggbbaa" in small letters, or "" for the toolkit\'s, not {value!r}')


def check(tokens: dict) -> None:
    """The tokens are in the format this tool knows: TokenError otherwise.
    Nothing unknown is let through: a section or a key written wrong would
    be a value that silently never arrives."""
    if tokens.get("format") != FORMAT:
        raise TokenError(f"format: this tool reads format {FORMAT}, the file says {tokens.get('format')!r}")
    for section, table in tokens.items():
        if section == "format":
            continue
        if section not in SECTIONS:
            raise TokenError(f"[{section}]: not a section of the format ({', '.join(SECTIONS)})")
        if not isinstance(table, dict):
            raise TokenError(f"{section}: a section, not a value")
        for key, value in table.items():
            where = f"{section}.{key}"
            if not KEY.match(key):
                raise TokenError(f"{where}: a key is small letters, digits and _, and says a role, not a number")
            if section == "color" and key in SCHEMES:
                if not isinstance(value, dict):
                    raise TokenError(f"{where}: a section of colours")
                for name, colour in value.items():
                    if not KEY.match(name):
                        raise TokenError(f"{where}.{name}: a key is small letters, digits and _")
                    _colour(f"{where}.{name}", colour)
            elif section == "color":
                _colour(where, value)
            elif section == "type" and key == "family":
                if not isinstance(value, str):
                    raise TokenError(f'{where}: the name of a font, or "" for the system\'s')
            elif section == "type" and key in WEIGHTS:
                _number(where, value, 100, 900)
            else:
                _number(where, value)
    space = tokens.get("space", {})
    unknown = [key for key in space if key not in SPACE]
    if unknown:
        raise TokenError(f"space.{unknown[0]}: the scale is closed ({', '.join(SPACE)})")
    steps = [space[key] for key in SPACE if key in space]
    if steps != sorted(set(steps)):
        raise TokenError("space: the scale grows from xxs to xxxl, with no two steps alike")


def read(path: Path = TOKENS) -> dict:
    with open(path, "rb") as f:
        tokens = tomllib.load(f)
    check(tokens)
    return tokens


def entries(tokens: dict) -> list[tuple[str, str, int | str, str]]:
    """Every value that is set, in the format's sections' order: (the CSS
    variable, the Python name, the value, its unit). An empty string is
    "the toolkit decides": it gives nothing."""
    found = []
    for section, (prefix, unit) in SECTIONS.items():
        for key, value in tokens.get(section, {}).items():
            if isinstance(value, dict) or value == "":
                continue
            if section == "type" and key in WEIGHTS:
                found.append((f"--weight-{key}", f"WEIGHT_{key}".upper(), value, ""))
            else:
                found.append((f"--{prefix}-{key.replace('_', '-')}", f"{prefix}_{key}".upper(), value,
                              unit if isinstance(value, int) else ""))
    return found


def scheme_colours(tokens: dict) -> list[str]:
    """The colours set for one scheme only (color.light, color.dark)."""
    return [f"color.{scheme}.{name}" for scheme in SCHEMES
            for name, colour in tokens.get("color", {}).get(scheme, {}).items() if colour != ""]


def css(tokens: dict) -> str:
    """gui/style.css: the values as variables of the whole display."""
    # GTK 4.24 with libadwaita 1.10 reads @media (prefers-color-scheme: dark)
    # without a word and never applies it when libadwaita turns dark (tried
    # on Windows, 10/11/2026): a colour by scheme needs another way, to be
    # chosen with the first app that sets one
    by_scheme = scheme_colours(tokens)
    if by_scheme:
        raise TokenError(f"{by_scheme[0]}: a colour by scheme is not made for GTK yet (the format's document)")
    lines = ["/* " + HEADER.replace("\n", "\n   ") + " */", ":root {"]
    for name, _python, value, unit in entries(tokens):
        quoted = isinstance(value, str) and not value.startswith("#")       # a font's name
        lines.append(f"  {name}: {chr(34) + value + chr(34) if quoted else value}{unit};")
    return "\n".join([*lines, "}"]) + "\n"


def values(tokens: dict) -> str:
    """gui/style_values.py: the same values for the code."""
    lines = ['"""' + HEADER + '"""', ""]
    lines += [f"{name} = {value!r}" for _css, name, value, _unit in entries(tokens)]
    return "\n".join(lines) + "\n"


def outputs(tokens: dict, package: Path = PACKAGE) -> dict[Path, str]:
    return {package / "gui" / "style.css": css(tokens), package / "gui" / "style_values.py": values(tokens)}


# -- what is written by hand where a value of the style should be ----------

_COMMENT = re.compile(r"/\*.*?\*/", re.S)
_VAR = re.compile(r"var\([^()]*\)")
_MEASURE = re.compile(r"(?<![\w.#-])(\d*\.?\d+)(px|pt|em|rem|ms|s)\b")
_HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")
_RGB = re.compile(r"\brgba?\(")


def hand_written(sheet: str) -> list[tuple[int, str]]:
    """The measures and the colours a style sheet writes itself instead of
    taking them from the variables: (line, what). A nought needs no unit
    and no variable."""
    def blank(match):                   # the lines keep their numbers
        return re.sub(r"[^\n]", " ", match.group())

    text = _VAR.sub(blank, _COMMENT.sub(blank, sheet))
    found = []
    for number, line in enumerate(text.splitlines(), 1):
        found += [(number, m.group()) for m in _MEASURE.finditer(line) if float(m.group(1)) != 0]
        found += [(number, m.group()) for pattern in (_HEX, _RGB) for m in pattern.finditer(line)]
    return found


MEASURES = ("spacing", "row_spacing", "column_spacing", "margin_top", "margin_bottom", "margin_start", "margin_end")


def literal_measures(source: str) -> list[tuple[int, str]]:
    """The spacings and the margins a module writes as numbers (spacing=12,
    set_margin_top(6)) instead of taking them from style_values: (line,
    what). A nought is no measure."""
    found = []
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, ast.Call):
            continue
        for keyword in node.keywords:
            value = keyword.value
            if keyword.arg in MEASURES and isinstance(value, ast.Constant) and _is_measure(value.value):
                found.append((value.lineno, f"{keyword.arg}={value.value}"))
        setter = node.func.attr if isinstance(node.func, ast.Attribute) else ""
        if setter.startswith("set_") and setter[4:] in MEASURES and node.args:
            value = node.args[0]
            if isinstance(value, ast.Constant) and _is_measure(value.value):
                found.append((value.lineno, f"{setter}({value.value})"))
    return sorted(found)


def _is_measure(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and value != 0


def by_hand(package: Path = PACKAGE) -> list[str]:
    """Every value of the style written by hand in the gui, as
    "gui/window.py:113 spacing=12"."""
    gui = package / "gui"
    found = []
    sheet = gui / "app.css"
    if sheet.is_file():
        found += [f"gui/app.css:{line} {what}" for line, what in hand_written(sheet.read_text(encoding="utf-8"))]
    for module in sorted(gui.glob("*.py")):
        if module.name != "style_values.py":
            found += [f"gui/{module.name}:{line} {what}"
                      for line, what in literal_measures(module.read_text(encoding="utf-8"))]
    return found


def first_difference(made: str, on_disk: str) -> str:
    """Where two texts part, for a message a person can act on."""
    ours, theirs = made.splitlines(), on_disk.splitlines()
    for number, (a, b) in enumerate(zip(ours, theirs), 1):      # noqa: B905  the lengths are told below
        if a != b:
            return f"line {number}: the tokens give {a.strip()!r}, the file has {b.strip()!r}"
    return f"the tokens give {len(ours)} lines, the file has {len(theirs)}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing: 1 if something is not as the tokens give")
    args = parser.parse_args()
    try:
        made = outputs(read())
    except (TokenError, tomllib.TOMLDecodeError) as e:
        print(f"{TOKENS.relative_to(ROOT).as_posix()}: {e}", file=sys.stderr)
        return 1
    if not args.check:
        for path, text in made.items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(path)
        return 0
    wrong = []
    for path, text in made.items():
        name = path.relative_to(ROOT).as_posix()
        if not path.is_file():
            wrong.append(f"{name}: missing, run tools/make_style.py")
        elif (on_disk := path.read_text(encoding="utf-8")) != text:
            wrong.append(f"{name}: not what the tokens give ({first_difference(text, on_disk)}): "
                         "edited by hand, or the tokens changed and the tool was not run")
    wrong += [f"{line}: written by hand, take it from the style's values" for line in by_hand()]
    print("\n".join(wrong) if wrong else "the style is what the tokens give")
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
